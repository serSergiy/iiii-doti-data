#!/usr/bin/env node
/**
 * Generate tools/draft-data.js — everything the draft page needs, as a <script> global.
 *
 * Written as a script rather than JSON because draft.html is opened over file://, where
 * fetch() of a sibling file is blocked by CORS but a <script src> is not.
 *
 * Re-run after any ingest:  node scripts/build-draft-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const stats = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'stats.json'), 'utf8'));
const coefs = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'coefficients.json'), 'utf8'));
const pools = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'hero-pools.json'), 'utf8')).pools;
// OpenDota spells two of the client's names differently.
const NAME_FIX = { 'Ringmaster': 'Ring Master', 'Outworld Destroyer': 'Outworld Devourer' };
let teams = {};
try { teams = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'teams.json'), 'utf8')); } catch {}

const C = Object.fromEntries(stats.columns.map((c, i) => [c, i]));

// Which dataset column feeds each official stat id. null = we have no source.
const STAT_SOURCE = {
  kills: 'kills', deaths: 'deaths', creepScore: 'derived', gpmX2: 'gpm',
  // madstone is an ESTIMATE (madstoneUses x 1.97), not a measured count — the UI must
  // badge it from stats.json.unvalidated. The game's own m_nAcquiredMadstone is NOT usable:
  // all ten players share one value on 43 of 63 maps.
  madstone: 'madstone', towerKills: 'towers', obsPlaced: 'obs',
  // watchers and lotuses come from the game's own m_iWatchersTaken / m_iLotusesTaken. Both
  // are genuinely per-player — neither is ever degenerate across a match — so unlike
  // madstone they are shipped as measured values.
  campsStacked: 'camps', runePickups: 'runes', watchers: 'watcher',
  lotuses: 'lotus', smokesUsed: 'smokes', roshanKills: 'roshan',
  // tormentor is PARTICIPATION, not the last hit — the game's own m_iTormentorKills
  // credits every hero who damaged it. Replay-only, so null on unparsed maps: falling
  // back to tormentorSelf would silently mix two semantics that differ by ~2.9x.
  teamfight: 'teamfight', stuns: 'stuns', tormentor: 'tormentorGame',
  courierKills: 'courier', firstBlood: 'firstBlood',
};

// player -> match -> stat values, only the fields the page scores on.
const byPlayer = {};
for (const r of stats.rows) {
  const acct = r[C.accountId];
  const mid = r[C.matchId];
  (byPlayer[acct] ??= {})[mid] = {
    kills: r[C.kills], deaths: r[C.deaths],
    creepScore: r[C.lastHits] + r[C.denies],       // official: last hit OR deny
    gpmX2: r[C.gpm], madstone: r[C.madstone], towerKills: r[C.towers],
    obsPlaced: r[C.obs], campsStacked: r[C.camps], runePickups: r[C.runes],
    watchers: r[C.watcher], lotuses: r[C.lotus], smokesUsed: r[C.smokes],
    roshanKills: r[C.roshan], teamfight: r[C.teamfight], stuns: r[C.stuns],
    tormentor: r[C.tormentorGame], courierKills: r[C.courier],
    firstBlood: r[C.firstBlood],
    pos: r[C.pos], heroId: r[C.heroId],
  };
}

// Roster per team, and which series each team played.
const rosters = {};
for (const [acct, p] of Object.entries(stats.players ?? {})) {
  const t = p.teamId ?? 0;
  (rosters[t] ??= []).push({ accountId: +acct, name: p.name });
}
for (const t of Object.keys(rosters)) {
  rosters[t].sort((a, b) => {
    const pa = Object.values(byPlayer[a.accountId] ?? {})[0]?.pos ?? 9;
    const pb = Object.values(byPlayer[b.accountId] ?? {})[0]?.pos ?? 9;
    return pa - pb;
  });
}

// hero display name -> id, so the prefix pools can be resolved to hero ids.
const heroName = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'heroes.json'), 'utf8'));
const npcToId = Object.fromEntries(Object.entries(heroName).map(([id, npc]) => [npc, +id]));
const localToId = JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'hero-localized.json'), 'utf8'));
const prefixes = {};
for (const [k, v] of Object.entries(pools)) {
  prefixes[k] = { uk: v.uk, bonus: v.bonus,
    heroIds: v.heroes.map(n => localToId[NAME_FIX[n] ?? n]).filter(x => x != null) };
}

const out = `/* Generated by scripts/build-draft-data.mjs — do not edit.
   league ${stats.leagueId} | ${Object.keys(stats.matches).length} matches | ${stats.generatedAt} */
window.TI_DATA = ${JSON.stringify({
  generatedAt: stats.generatedAt,
  prefixes,
  heroNames: localToId,
  coefficients: coefs.stats.map(({ id, uk, color, kind, points, base, definition }) =>
    ({ id, uk, color, kind, points, base, definition, source: STAT_SOURCE[id] })),
  teams: Object.entries(rosters).map(([teamId, players]) => ({
    teamId: +teamId, teamName: teams[teamId] ?? String(teamId), players,
  })).sort((a, b) => a.teamName.localeCompare(b.teamName)),
  matches: stats.matches,
  byPlayer,
})};
`;
fs.writeFileSync(path.join(ROOT, 'tools', 'draft-data.js'), out);
const kb = (fs.statSync(path.join(ROOT, 'tools', 'draft-data.js')).size / 1024).toFixed(0);
console.log(`tools/draft-data.js — ${kb} KB, ${Object.keys(stats.matches).length} matches, ${Object.keys(byPlayer).length} players`);
