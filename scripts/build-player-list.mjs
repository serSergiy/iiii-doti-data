#!/usr/bin/env node
/**
 * Generate tools/players-data.js from the committed dataset.
 *
 * Written as a plain <script> assigning a global, NOT as JSON: banner-input.html is opened
 * over file://, where fetch() of a sibling file is blocked by CORS but a <script src> is
 * not. Re-run whenever the roster grows.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const stats = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'stats.json'), 'utf8'));

const byTeam = new Map();
for (const [accountId, p] of Object.entries(stats.players ?? {})) {
  const t = p.teamId ?? 0;
  if (!byTeam.has(t)) byTeam.set(t, []);
  byTeam.get(t).push({ accountId: +accountId, name: p.name });
}

// Which roles a player actually appeared in, so the picker can order sensibly.
const posIdx = stats.columns.indexOf('pos');
const acctIdx = stats.columns.indexOf('accountId');
const posOf = new Map();
for (const r of stats.rows) {
  if (r[posIdx] != null && !posOf.has(r[acctIdx])) posOf.set(r[acctIdx], r[posIdx]);
}

// Team names are not in the match listing (radiant_team_name comes back null), so resolve
// them once and cache — an optgroup labelled "9247354" helps nobody.
const cacheFile = path.join(ROOT, 'config', 'teams.json');
let teamNames = {};
try { teamNames = JSON.parse(fs.readFileSync(cacheFile, 'utf8')); } catch { /* first run */ }

for (const teamId of byTeam.keys()) {
  if (!teamId || teamNames[teamId]) continue;
  try {
    const r = await fetch(`https://api.opendota.com/api/teams/${teamId}`, {
      headers: { 'User-Agent': 'ti2026-fantasy-data/0.1' },
    });
    if (r.ok) teamNames[teamId] = (await r.json()).name ?? String(teamId);
    await new Promise((res) => setTimeout(res, 1100)); // free tier pacing
  } catch { /* leave unresolved; the id still renders */ }
}
fs.writeFileSync(cacheFile, JSON.stringify(teamNames, null, 1));

const teams = [...byTeam.entries()]
  .map(([teamId, players]) => ({
    teamId,
    teamName: teamNames[teamId] ?? String(teamId),
    players: players
      .map((p) => ({ ...p, pos: posOf.get(p.accountId) ?? null }))
      .sort((a, b) => (a.pos ?? 9) - (b.pos ?? 9)),
  }))
  .sort((a, b) => a.teamName.localeCompare(b.teamName));

const out = `/* Generated by scripts/build-player-list.mjs — do not edit by hand.
   Source: data/stats.json, league ${stats.leagueId}, ${stats.generatedAt}
   ${teams.length} teams, ${Object.keys(stats.players ?? {}).length} players. */
window.TI_PLAYERS = ${JSON.stringify(teams, null, 1)};
`;

fs.writeFileSync(path.join(ROOT, 'tools', 'players-data.js'), out);
console.log(`tools/players-data.js — ${teams.length} teams, ${Object.keys(stats.players ?? {}).length} players`);
